package querier

import (
	"context"
	"fmt"
	"net/http"

	"github.com/go-kit/log"
	"github.com/go-kit/log/level"
	"github.com/prometheus/prometheus/storage"

	"github.com/cortexproject/cortex/pkg/cortexpb"
	"github.com/cortexproject/cortex/pkg/ingester/client"
	"github.com/cortexproject/cortex/pkg/util"
	"github.com/cortexproject/cortex/pkg/util/concurrency"
	util_log "github.com/cortexproject/cortex/pkg/util/log"
)

// Queries are a set of matchers with time ranges - should not get into megabytes
const maxRemoteReadQuerySize = 1024 * 1024

// maxRemoteReadQueries is the maximum number of sub-queries allowed in a single
// remote read request. Clients normally send one sub-query per request, so this
// is a very generous ceiling that still bounds goroutine fan-out and the
// amplified downstream load against ingesters and store-gateways. Without this
// cap, a single ~1 MiB protobuf body can encode hundreds of thousands of
// sub-queries (a minimal QueryRequest is 2 bytes on the wire), each of which
// spawns its own goroutine and gRPC fan-out, enabling cross-tenant DoS.
const maxRemoteReadQueries = 100

// maxRemoteReadQueryConcurrency bounds the number of sub-queries from a single
// remote read request that are executed in parallel. This caps the goroutine
// and downstream RPC fan-out generated by one request, independent of how many
// sub-queries the client supplied.
const maxRemoteReadQueryConcurrency = 10

// RemoteReadHandler handles Prometheus remote read requests.
func RemoteReadHandler(q storage.Queryable, logger log.Logger) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		ctx := r.Context()
		var req client.ReadRequest
		logger := util_log.WithContext(r.Context(), logger)
		if err := util.ParseProtoReader(ctx, r.Body, int(r.ContentLength), maxRemoteReadQuerySize, &req, util.RawSnappy); err != nil {
			level.Error(logger).Log("msg", "failed to parse proto", "err", err.Error())
			http.Error(w, err.Error(), http.StatusBadRequest)
			return
		}

		// Reject requests that attempt to pack an unreasonable number of
		// sub-queries into a single body. Without this bound, a small
		// snappy-compressed body can encode hundreds of thousands of
		// sub-queries, each of which fans out to every ingester and
		// store-gateway in the cell.
		if len(req.Queries) > maxRemoteReadQueries {
			err := fmt.Errorf("too many queries in remote read request: %d (max: %d)", len(req.Queries), maxRemoteReadQueries)
			level.Warn(logger).Log("msg", "rejecting remote read request with too many queries", "queries", len(req.Queries), "max", maxRemoteReadQueries)
			http.Error(w, err.Error(), http.StatusBadRequest)
			return
		}

		// Fetch samples for all queries in parallel, but bound the fan-out so a
		// single request cannot exhaust the querier or saturate shared
		// ingester/store-gateway capacity.
		resp := client.ReadResponse{
			Results: make([]*client.QueryResponse, len(req.Queries)),
		}

		jobs := make([]interface{}, len(req.Queries))
		for i, qr := range req.Queries {
			jobs[i] = &remoteReadJob{idx: i, qr: qr}
		}

		err := concurrency.ForEach(ctx, jobs, maxRemoteReadQueryConcurrency, func(ctx context.Context, job interface{}) error {
			j := job.(*remoteReadJob)

			from, to, matchers, err := client.FromQueryRequest(j.qr)
			if err != nil {
				return err
			}

			querier, err := q.Querier(ctx, int64(from), int64(to))
			if err != nil {
				return err
			}

			params := &storage.SelectHints{
				Start: int64(from),
				End:   int64(to),
			}
			seriesSet := querier.Select(false, params, matchers...)
			result, err := seriesSetToQueryResponse(seriesSet)
			if err != nil {
				return err
			}
			resp.Results[j.idx] = result
			return nil
		})
		if err != nil {
			http.Error(w, err.Error(), http.StatusBadRequest)
			return
		}
		w.Header().Add("Content-Type", "application/x-protobuf")
		if err := util.SerializeProtoResponse(w, &resp, util.RawSnappy); err != nil {
			level.Error(logger).Log("msg", "error sending remote read response", "err", err)
		}
	})
}

// remoteReadJob carries one sub-query and the destination index in the
// response slice so that bounded parallel execution preserves ordering.
type remoteReadJob struct {
	idx int
	qr  *client.QueryRequest
}

func seriesSetToQueryResponse(s storage.SeriesSet) (*client.QueryResponse, error) {
	result := &client.QueryResponse{}

	for s.Next() {
		series := s.At()
		samples := []cortexpb.Sample{}
		it := series.Iterator()
		for it.Next() {
			t, v := it.At()
			samples = append(samples, cortexpb.Sample{
				TimestampMs: t,
				Value:       v,
			})
		}
		if err := it.Err(); err != nil {
			return nil, err
		}
		result.Timeseries = append(result.Timeseries, cortexpb.TimeSeries{
			Labels:  cortexpb.FromLabelsToLabelAdapters(series.Labels()),
			Samples: samples,
		})
	}

	return result, s.Err()
}
