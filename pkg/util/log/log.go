type contextKey int

const (
	headerMapContextKey contextKey = 0

	HeaderPropagationStringForRequestLogging string = "x-http-header-forwarding-logging"
)

var (
	// Logger is a shared go-kit logger.
	// TODO: Change all components to take a non-global logger via their constructors.
	// Prefer accepting a non-global logger as an argument.
	Logger = kitlog.NewNopLogger()

	logMessages = prometheus.NewCounterVec(prometheus.CounterOpts{
		Name: "log_messages_total",
		Help: "Total number of log messages.",
	}, []string{"level"})

	supportedLevels = []level.Value{
		level.DebugValue(),
		level.InfoValue(),
		level.WarnValue(),
		level.ErrorValue(),
	}
)

func init() {
	prometheus.MustRegister(logMessages)
}

// InitLogger initialises the global gokit logger (util_log.Logger) and overrides the
// default logger for the server.
func InitLogger(cfg *server.Config) {
	l, err := NewPrometheusLogger(cfg.LogLevel, cfg.LogFormat)
	if err != nil {
		panic(err)
	}

	// when use util_log.Logger, skip 3 stack frames.
	Logger = log.With(l, "caller", log.Caller(3))

	// cfg.Log wraps log function, skip 4 stack frames to get caller information.
	// this works in go 1.12, but doesn't work in versions earlier.
	// it will always shows the wrapper function generated by compiler
	// marked <autogenerated> in old versions.
	cfg.Log = logging.GoKit(log.With(l, "caller", log.Caller(4)))
}

// PrometheusLogger exposes Prometheus counters for each of go-kit's log levels.
type PrometheusLogger struct {
	logger log.Logger
}

// NewPrometheusLogger creates a new instance of PrometheusLogger which exposes
// Prometheus counters for various log levels.
func NewPrometheusLogger(l logging.Level, format logging.Format) (log.Logger, error) {
	logger := log.NewLogfmtLogger(log.NewSyncWriter(os.Stderr))
	if format.String() == "json" {
		logger = log.NewJSONLogger(log.NewSyncWriter(os.Stderr))
	}
	logger = level.NewFilter(logger, LevelFilter(l.String()))

	// Initialise counters for all supported levels:
	for _, level := range supportedLevels {
		logMessages.WithLabelValues(level.String())
	}

	logger = &PrometheusLogger{
		logger: logger,
	}

	// return a Logger without caller information, shouldn't use directly
	logger = log.With(logger, "ts", log.DefaultTimestampUTC)
	return logger, nil
}

// Log increments the appropriate Prometheus counter depending on the log level.
func (pl *PrometheusLogger) Log(kv ...interface{}) error {
	pl.logger.Log(kv...)
	l := "unknown"
	for i := 1; i < len(kv); i += 2 {
		if v, ok := kv[i].(level.Value); ok {
			l = v.String()
			break
		}
	}
	logMessages.WithLabelValues(l).Inc()
	return nil
}

// CheckFatal prints an error and exits with error code 1 if err is non-nil
func CheckFatal(location string, err error) {
	if err != nil {
		logger := level.Error(Logger)
		if location != "" {
			logger = log.With(logger, "msg", "error "+location)
		}
		// %+v gets the stack trace from errors using github.com/pkg/errors
		logger.Log("err", fmt.Sprintf("%+v", err))
		os.Exit(1)
	}
}

// TODO(dannyk): remove once weaveworks/common updates to go-kit/log
//
//	-> we can then revert to using Level.Gokit
func LevelFilter(l string) level.Option {
	switch l {
	case "debug":
		return level.AllowDebug()
	case "info":
		return level.AllowInfo()
	case "warn":
		return level.AllowWarn()
	case "error":
		return level.AllowError()
	default:
		return level.AllowAll()
	}
}

func HeaderMapFromContext(ctx context.Context) map[string]string {
	headerMap, ok := ctx.Value(headerMapContextKey).(map[string]string)
	if !ok {
		return nil
	}
	return headerMap
}

func ContextWithHeaderMap(ctx context.Context, headerMap map[string]string) context.Context {
	return context.WithValue(ctx, headerMapContextKey, headerMap)
}

// InjectHeadersIntoHTTPRequest injects the logging header map from the context into the request headers.
// Credential-bearing header names (see IsSensitiveRequestHeader) are silently
// skipped so a compromised or misconfigured upstream cannot cause end-user
// bearer tokens or session cookies to be re-propagated onto outbound internal
// HTTP requests.
func InjectHeadersIntoHTTPRequest(headerMap map[string]string, request *http.Request) {
	for header, contents := range headerMap {
		if IsSensitiveRequestHeader(header) {
			continue
		}
		request.Header.Add(header, contents)
	}
}

func ContextWithHeaderMapFromMetadata(ctx context.Context, md metadata.MD) context.Context {
	headersSlice, ok := md[HeaderPropagationStringForRequestLogging]
	if !ok || len(headersSlice)%2 == 1 {
		return ctx
	}

	headerMap := make(map[string]string)
	for i := 0; i < len(headersSlice); i += 2 {
		// Drop credential-bearing header names that were propagated to us via
		// gRPC metadata so they cannot be re-logged on this component or
		// re-forwarded further downstream.
		if IsSensitiveRequestHeader(headersSlice[i]) {
			continue
		}
		headerMap[headersSlice[i]] = headersSlice[i+1]
	}

	return ContextWithHeaderMap(ctx, headerMap)
}

// sensitiveRequestHeaderDenyList is the set of HTTP request header names whose
// values must never be captured into logs, re-injected into outbound HTTP
// requests, or propagated to downstream Cortex components via gRPC metadata.
// The feature backed by -api.http-request-headers-to-log stores the raw value
// as a structured log field on every request log line; naming a credential-
// bearing header would therefore write end-user bearer tokens or session
// cookies verbatim into service logs. Header names are compared
// case-insensitively.
var sensitiveRequestHeaderDenyList = map[string]struct{}{
	"authorization":                  {},
	"proxy-authorization":            {},
	"cookie":                         {},
	"set-cookie":                     {},
	"x-amz-security-token":           {},
	"x-auth-token":                   {},
	"x-api-key":                      {},
	"x-csrf-token":                   {},
	"x-xsrf-token":                   {},
	"x-vault-token":                  {},
	"x-goog-iam-authorization-token": {},
}

// IsSensitiveRequestHeader reports whether the given HTTP header name is on
// the credential-header deny-list and must not be captured for logging or
// propagation. Comparison is case-insensitive and tolerant of surrounding
// whitespace.
func IsSensitiveRequestHeader(name string) bool {
	_, ok := sensitiveRequestHeaderDenyList[strings.ToLower(strings.TrimSpace(name))]
	return ok
}

// FilterSensitiveHeaderNames returns the subset of the given operator-supplied
// header names that are safe to log, together with the list of names that were
// rejected because they are on the credential-header deny-list.
func FilterSensitiveHeaderNames(names []string) (safe []string, rejected []string) {
	for _, name := range names {
		if IsSensitiveRequestHeader(name) {
			rejected = append(rejected, name)
			continue
		}
		safe = append(safe, name)
	}
	return safe, rejected
}
